CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    senha_hash VARCHAR(255) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE perfis (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(24) NOT NULL UNIQUE
);

CREATE TABLE usuario_perfis (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
    perfil_id BIGINT NOT NULL REFERENCES perfis(id),
    CONSTRAINT uq_usuario_perfis_usuario_perfil UNIQUE (usuario_id, perfil_id)
);

CREATE TABLE recursos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(160) NOT NULL,
    tipo VARCHAR(24) NOT NULL,
    localizacao VARCHAR(160),
    competencia VARCHAR(240),
    capacidade INTEGER CHECK (capacidade IS NULL OR capacidade >= 0),
    quantidade_total INTEGER CHECK (quantidade_total IS NULL OR quantidade_total >= 0),
    restrito BOOLEAN NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    docente_usuario_id BIGINT UNIQUE REFERENCES usuarios(id)
);

CREATE TABLE reservas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitante_id BIGINT NOT NULL REFERENCES usuarios(id),
    inicio TIMESTAMP WITH TIME ZONE NOT NULL,
    fim TIMESTAMP WITH TIME ZONE NOT NULL,
    status VARCHAR(32) NOT NULL,
    finalidade VARCHAR(500) NOT NULL,
    criada_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_reservas_intervalo CHECK (fim > inicio)
);

CREATE TABLE reserva_recursos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reserva_id BIGINT NOT NULL REFERENCES reservas(id),
    recurso_id BIGINT NOT NULL REFERENCES recursos(id),
    quantidade INTEGER NOT NULL CHECK (quantidade > 0),
    CONSTRAINT uq_reserva_recursos_reserva_recurso UNIQUE (reserva_id, recurso_id)
);

CREATE TABLE aprovacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reserva_id BIGINT NOT NULL REFERENCES reservas(id),
    responsavel_id BIGINT NOT NULL REFERENCES usuarios(id),
    decisao VARCHAR(16) NOT NULL,
    justificativa VARCHAR(1000),
    decidida_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE bloqueios_manutencao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recurso_id BIGINT NOT NULL REFERENCES recursos(id),
    criado_por_id BIGINT NOT NULL REFERENCES usuarios(id),
    inicio TIMESTAMP WITH TIME ZONE NOT NULL,
    fim TIMESTAMP WITH TIME ZONE NOT NULL,
    justificativa VARCHAR(500) NOT NULL,
    CONSTRAINT ck_bloqueios_intervalo CHECK (fim > inicio)
);

CREATE TABLE movimentacoes_material (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reserva_id BIGINT NOT NULL REFERENCES reservas(id),
    recurso_id BIGINT NOT NULL REFERENCES recursos(id),
    responsavel_id BIGINT NOT NULL REFERENCES usuarios(id),
    tipo VARCHAR(16) NOT NULL,
    quantidade INTEGER NOT NULL CHECK (quantidade > 0),
    registrada_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE auditorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
    acao VARCHAR(80) NOT NULL,
    tipo_entidade VARCHAR(80) NOT NULL,
    entidade_id BIGINT,
    dados_anteriores TEXT,
    dados_novos TEXT,
    ocorrida_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE eventos_conflito (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recurso_id BIGINT NOT NULL REFERENCES recursos(id),
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
    intervalo_inicio TIMESTAMP WITH TIME ZONE NOT NULL,
    intervalo_fim TIMESTAMP WITH TIME ZONE NOT NULL,
    motivo VARCHAR(500) NOT NULL,
    registrado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_eventos_conflito_intervalo CHECK (intervalo_fim > intervalo_inicio)
);

CREATE TABLE notificacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reserva_id BIGINT REFERENCES reservas(id),
    destinatario_id BIGINT NOT NULL REFERENCES usuarios(id),
    canal VARCHAR(40) NOT NULL,
    status VARCHAR(16) NOT NULL,
    detalhe_falha VARCHAR(500),
    mensagem VARCHAR(2000) NOT NULL,
    criada_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    enviada_em TIMESTAMP WITH TIME ZONE
);

CREATE INDEX idx_recursos_tipo_ativo ON recursos (tipo, ativo);
CREATE INDEX idx_recursos_localizacao ON recursos (localizacao);
CREATE INDEX idx_recursos_competencia ON recursos (competencia);
CREATE INDEX idx_reservas_intervalo ON reservas (inicio, fim);
CREATE INDEX idx_reservas_solicitante_inicio ON reservas (solicitante_id, inicio);
CREATE INDEX idx_reserva_recursos_recurso ON reserva_recursos (recurso_id);
CREATE INDEX idx_aprovacoes_responsavel_data ON aprovacoes (responsavel_id, decidida_em);
CREATE INDEX idx_bloqueios_recurso_intervalo ON bloqueios_manutencao (recurso_id, inicio, fim);
CREATE INDEX idx_movimentacoes_reserva_data ON movimentacoes_material (reserva_id, registrada_em);
CREATE INDEX idx_auditorias_entidade_data ON auditorias (tipo_entidade, entidade_id, ocorrida_em);
CREATE INDEX idx_eventos_conflito_recurso_data ON eventos_conflito (recurso_id, registrado_em);
CREATE INDEX idx_notificacoes_reserva_data ON notificacoes (reserva_id, criada_em);

